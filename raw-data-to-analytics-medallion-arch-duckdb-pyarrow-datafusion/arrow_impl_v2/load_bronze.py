"""Bronze landing stage - incremental raw ingestion over Parquet.

Mirrors duck_impl_v2/load_bronze.py: scans the shared ``data/`` landing
folder for ``events_arr_*.csv`` files and only ingests CSV files that have
not already been landed. Every new source CSV becomes its own Parquet file
under ``storage/bronze/`` so re-runs never reprocess or duplicate raw rows.
"""

import sys
from datetime import UTC, datetime
from pathlib import Path

import pyarrow as pa
import pyarrow.csv as pv
import pyarrow.parquet as pq

PROJECT_ROOT = Path(__file__).resolve().parent
REPO_ROOT = PROJECT_ROOT.parent

LANDING_DIR = REPO_ROOT / "data"
BRONZE_DIR = PROJECT_ROOT / "storage" / "bronze"
BRONZE_DIR.mkdir(parents=True, exist_ok=True)

RAW_COLUMNS = [
    "event_date",
    "country",
    "channel",
    "user_id",
    "order_id",
    "revenue",
]

BRONZE_SCHEMA = pa.schema(
    [(name, pa.string()) for name in RAW_COLUMNS]
    + [
        pa.field("_ingested_at", pa.timestamp("ns")),
        pa.field("_source_file", pa.string()),
    ]
)

# Scan landing folder for CSVs generated by arrow_impl_v2/generate_dirty_data.py
csv_files = sorted(LANDING_DIR.glob("events_arr_*.csv"))

if not csv_files:
    print("No CSV files found in landing directory.")
    sys.exit(0)

# A Parquet file whose stem matches an already-landed CSV means it was ingested.
landed_stems = {p.stem for p in BRONZE_DIR.glob("*.parquet")}
new_files = [f for f in csv_files if f.stem not in landed_stems]

if not new_files:
    print("No new CSV files to ingest.")
else:
    for file_path in new_files:
        # Read with an all-string schema (schema-on-read, never fails on dirty data)
        convert_options = pv.ConvertOptions(
            column_types={col: pa.string() for col in RAW_COLUMNS}
        )
        table = pv.read_csv(file_path, convert_options=convert_options)

        # Attach lineage/audit metadata
        ingested_at = datetime.now(UTC)
        table = table.append_column(
            "_ingested_at",
            pa.array([ingested_at] * table.num_rows, pa.timestamp("ns")),
        )
        table = table.append_column(
            "_source_file",
            pa.array([file_path.name] * table.num_rows, pa.string()),
        )

        dest_path = BRONZE_DIR / f"{file_path.stem}.parquet"
        pq.write_table(table, dest_path, compression="snappy")
        print(f"Ingested {file_path.name} into bronze.events ({table.num_rows:,} rows)")

total_bronze = sum(pq.read_metadata(p).num_rows for p in BRONZE_DIR.glob("*.parquet"))
print(f"Total Bronze Rows: {total_bronze:,}")
